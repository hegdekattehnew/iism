/**
 * The icon set (Sprint 78, BL-19.7, ADR-087).
 *
 * Thirty-six icons drawn as strokes on a 24 x 24 grid, written here and nowhere else: no icon
 * package, no image request (the CSP blocks remote images anyway), and nothing to download on a
 * low-end phone. The colour is `currentColor`, so an icon takes its text colour from a token and
 * follows the theme with it.
 *
 * **Each icon is its own export, built by a call marked pure**, so a route that imports three pays
 * for three: the header's imports are on every route's first load, and `/profile` is within a few
 * kilobytes of the ceiling (CLAUDE.md, "The header's import graph"). Do not replace this with one
 * `<Icon name="..." />` that looks a shape up in a table: that puts the whole table on every route.
 *
 * **An icon is decorative unless it is given a `title`.** Beside a word it repeats the word, so a
 * screen reader should skip it (`aria-hidden`); on its own it is a control or a status and needs a
 * name (`role="img"` and `aria-label`). `tests/test_icon_shapes.py` keeps the phone's copy of the
 * shapes (`mobile/src/ui/icon-shapes.ts`, generated by `scripts/sync_mobile_tokens.py`) the same.
 *
 * The line this file keeps to: `makeIcon("Name", ["path", ...])`, one icon per statement, paths as
 * plain string literals. The sync script reads exactly that.
 */
import type { SVGProps } from "react";

export type IconProps = Omit<SVGProps<SVGSVGElement>, "children" | "title"> & {
  /** Gives the icon a name for assistive technology. Omit it when the icon sits beside its word. */
  title?: string;
};

function makeIcon(displayName: string, paths: readonly string[]) {
  function Icon({ title, className = "h-5 w-5", ...rest }: IconProps) {
    return (
      <svg
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
        className={className}
        focusable="false"
        {...(title ? { role: "img", "aria-label": title } : { "aria-hidden": true })}
        {...rest}
      >
        {paths.map((d) => (
          <path key={d} d={d} />
        ))}
      </svg>
    );
  }
  Icon.displayName = `${displayName}Icon`;
  return Icon;
}

