"""Generate the mobile app's colour tokens from the web's `globals.css` (Sprint 62, ADR-072).

`globals.css` is the only file in the web app that names a colour, and the mobile app has the same
rule for the same reason: two hand-copied palettes drift, and a colour defined for one theme and
missing in the other renders invisible in it. So the mobile tokens are **generated**, never edited:

    .venv/bin/python scripts/sync_mobile_tokens.py          # write mobile/src/theme/tokens.ts
    .venv/bin/python scripts/sync_mobile_tokens.py --check  # exit 1 if it is out of date

`tests/test_mobile_foundations.py` runs the check. Colours are carried over as the `light` and
`dark` tables: shadows are CSS and a phone uses elevation, and an `rgb(15 23 42 / 0.45)` overlay
becomes `rgba(15, 23, 42, 0.45)`, the form every React Native version reads. Since Sprint 77
(ADR-086) the **radius** (`--r-*`) and the **type scale** (`--type-*`, a size and an English line
height in px) are carried over too, as `radius` and `type`, so a corner and a step of text are the
same size on both. A value is a colour **only if it is a colour literal**: a radius or a duration
in the first `:root` block is never emitted as one.

Since Sprint 78 (ADR-087) it also writes `mobile/src/ui/icon-shapes.ts`, the icon paths, read from
the web's `components/ui/icons.tsx` (one `makeIcon("Name", ["path", ...])` per icon), so a shape is
drawn once and both clients show the same one.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "web" / "src" / "app" / "globals.css"
TARGET = ROOT / "mobile" / "src" / "theme" / "tokens.ts"
ICONS_SOURCE = ROOT / "web" / "src" / "components" / "ui" / "icons.tsx"
ICONS_TARGET = ROOT / "mobile" / "src" / "ui" / "icon-shapes.ts"

_DECLARATION = re.compile(r"--([a-z0-9-]+)\s*:\s*([^;]+);")
_SPACE_RGB = re.compile(r"rgb\(\s*(\d+)\s+(\d+)\s+(\d+)\s*/\s*([\d.]+)\s*\)")
_HEX = re.compile(r"#[0-9a-fA-F]{3,8}")
_REM = re.compile(r"([\d.]+)rem")
_ICON = re.compile(r'/\*#__PURE__\*/ makeIcon\("([A-Za-z]+)",\s*\[(.*?)\]\)', re.S)
_STRING = re.compile(r'"([^"]*)"')


def _block(css: str, opener: str) -> str:
    """The text between the braces that follow `opener`, counting nesting."""
    start = css.index(opener) + len(opener)
    start = css.index("{", start) + 1
    depth, i = 1, start
    while depth:
        depth += {"{": 1, "}": -1}.get(css[i], 0)
        i += 1
    return css[start : i - 1]


def _colours(block: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for name, value in _DECLARATION.findall(block):
        if name.startswith("shadow"):
            continue
        value = value.strip()
        match = _SPACE_RGB.fullmatch(value)
        if match:
            value = f"rgba({match[1]}, {match[2]}, {match[3]}, {match[4]})"
        elif not _HEX.fullmatch(value):
            continue  # a radius, a duration, a type size: not a colour
        out[name] = value
    return out


def _px(value: str) -> int | float:
    """`0.8125rem` as 13: rem is 16 px, and a whole number is written as one."""
    match = _REM.fullmatch(value.strip())
    assert match, f"not a rem value: {value!r}"  # noqa: S101
    px = round(float(match[1]) * 16, 2)
    return int(px) if px == int(px) else px


def _scale(block: str, prefix: str) -> dict[str, str]:
    return {
        name[len(prefix) :]: value.strip()
        for name, value in _DECLARATION.findall(block)
        if name.startswith(prefix)
    }


def _camel(name: str) -> str:
    head, *rest = name.split("-")
    return head + "".join(part.capitalize() for part in rest)


def render(css: str) -> str:
    light = _colours(_block(css, ":root"))
    dark_overrides = _colours(_block(_block(css, "@media (prefers-color-scheme: dark)"), ":root"))
    dark = {**light, **dark_overrides}
    assert set(dark) == set(light), "a dark token with no light value"  # noqa: S101

    def table(name: str, values: dict[str, str]) -> str:
        rows = "".join(f'  {_camel(k)}: "{v}",\n' for k, v in values.items())
        return f"export const {name} = {{\n{rows}}} as const;\n"

    root = _block(css, ":root")
    radius = {k: _px(v) for k, v in _scale(root, "r-").items()}
    sizes = {k: v for k, v in _scale(root, "type-").items() if not k.endswith("-lh")}
    heights = {k[: -len("-lh")]: v for k, v in _scale(root, "type-").items() if k.endswith("-lh")}
    assert set(sizes) == set(heights), "a type step with no line height"  # noqa: S101
    radius_rows = "".join(f"  {k}: {v},\n" for k, v in radius.items())
    type_rows = "".join(
        f"  {k}: {{ size: {_px(v)}, lineHeight: {_px(heights[k])} }},\n" for k, v in sizes.items()
    )

    return (
        "// GENERATED by scripts/sync_mobile_tokens.py from web/src/app/globals.css. Do not edit:\n"
        "// change the web's tokens and run the script. `tests/test_mobile_foundations.py` fails\n"
        "// when this file is not what the script would write.\n\n"
        + table("light", light)
        + "\n"
        + table("dark", dark)
        + "\nexport type Colours = { [K in keyof typeof light]: string };\n"
        + f"\nexport const radius = {{\n{radius_rows}}} as const;\n"
        + f"\nexport const type = {{\n{type_rows}}} as const;\n"
    )


def render_icons(tsx: str) -> str:
    icons = {name: _STRING.findall(body) for name, body in _ICON.findall(tsx)}
    assert icons, "no icons found in the web's icons.tsx"  # noqa: S101
    assert all(icons.values()), "an icon with no shape"  # noqa: S101
    rows = "".join(
        f"  {name}: [\n" + "".join(f'    "{d}",\n' for d in paths) + "  ],\n"
        for name, paths in icons.items()
    )
    return (
        "// GENERATED by scripts/sync_mobile_tokens.py from web/src/components/ui/icons.tsx.\n"
        "// Do not edit: draw the icon on the web and run the script.\n"
        "// `tests/test_icon_shapes.py` fails when this is not what the script would write.\n\n"
        f"export const SHAPES = {{\n{rows}}} as const;\n\n"
        "export type IconName = keyof typeof SHAPES;\n"
    )


def main() -> int:
    outputs = [
        (TARGET, render(SOURCE.read_text(encoding="utf-8"))),
        (ICONS_TARGET, render_icons(ICONS_SOURCE.read_text(encoding="utf-8"))),
    ]
    if "--check" in sys.argv:
        stale = [
            t
            for t, wanted in outputs
            if (t.read_text(encoding="utf-8") if t.exists() else "") != wanted
        ]
        for t in stale:
            print(f"{t.relative_to(ROOT)} is out of date: run scripts/sync_mobile_tokens.py")
        return 1 if stale else 0
    for t, wanted in outputs:
        t.parent.mkdir(parents=True, exist_ok=True)
        t.write_text(wanted, encoding="utf-8")
        print(f"wrote {t.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
