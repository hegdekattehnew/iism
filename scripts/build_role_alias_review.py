"""Write the role-alias reviewer's workbook (Sprint 71, BL-12.12).

    .venv/bin/python scripts/build_role_alias_review.py

The aliases in `api/modules/skills/role_aliases.py` are engineering's draft of how people name their
work; the backlog says they need someone who knows the labour market. This is that person's copy:
one row per surface form with the role it leads to and empty columns to keep, change or retire it.
It is built from the dict alone (deterministic, no database), so `tests/test_role_alias_review.py`
can fail when the committed copy is stale. The decisions are applied on `/admin`, never by editing
this file.
"""

import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from xlsx_min import sheet, write_workbook  # noqa: E402

from api.modules.skills.role_aliases import ROLE_ALIASES  # noqa: E402

OUT = ROOT / "docs" / "IISM-Role-Aliases-for-Review.xlsx"

DEVANAGARI = re.compile(r"[ऀ-ॿ]")


def language(surface: str) -> str:
    """Devanagari, or Latin script (English and romanised Hindi cannot be told apart by a script
    check, and guessing which is exactly the judgement the reviewer is here to make)."""
    return "Devanagari" if DEVANAGARI.search(surface) else "Latin script"


def build_sheets() -> list[tuple[str, str]]:
    ordered = sorted(ROLE_ALIASES.items(), key=lambda kv: (kv[1].lower(), kv[0]))
    per_role = Counter(ROLE_ALIASES.values())
    rows = [
        [
            "What a person types",
            "Script",
            "Leads to this role",
            "Other forms for the same role",
            "Keep / change / retire",
            "Your note (what people really say, or the right role)",
        ]
    ]
    for surface, role in ordered:
        rows.append([surface, language(surface), role, str(per_role[role] - 1), "", ""])

    by_script = Counter(language(s) for s in ROLE_ALIASES)
    summary = [
        ["What this is", "Value"],
        [
            "Status",
            "UNREVIEWED. Engineering drafted these from public knowledge of how entry-level "
            "work is named in India. Nobody who works in these labour markets has read them. "
            "Every row is live until someone retires it.",
        ],
        ["Surface forms", str(len(ROLE_ALIASES))],
        ["Roles they lead to", str(len(per_role))],
        ["Latin script (English and romanised Hindi)", str(by_script["Latin script"])],
        ["Devanagari", str(by_script["Devanagari"])],
        [
            "What to look for",
            "A form that leads somewhere a person would not expect; a word people really say "
            "that is missing; a role at the wrong level (a trainee where a worker is meant). "
            "Better to retire a form than to keep a guess: a wrong answer here is a confident "
            "wrong answer.",
        ],
        [
            "How decisions are applied",
            "An admin-tier operator adds, changes or retires an alias on /admin. A retired alias "
            "stays retired when the seed list is reloaded. Do not edit this file expecting the "
            "product to change.",
        ],
        [
            "Left out on purpose",
            "Words that name no single role: helper, mechanic, machine operator, nurse, "
            "loader, packer, bouncer, anganwadi worker. Jobs the national list has no role "
            "for: housemaid, maid, accountant, turner, lathe operator. Say if you think any "
            "of these has an honest target.",
        ],
        [
            "How well it works",
            "Run `make evaluate-roles` against the full national import. It scores titles written "
            "before the aliases, and reports the titles kept aside separately.",
        ],
    ]
    summary_styles = [["header", "header"]] + [["bold", "normal"] for _ in summary[1:]]
    return [
        ("Summary", sheet(summary, [34, 110], freeze=False, filt=False, styles=summary_styles)),
        ("Aliases", sheet(rows, [30, 14, 52, 14, 22, 52])),
    ]


def main() -> None:
    write_workbook(OUT, build_sheets())
    print(f"{len(ROLE_ALIASES)} aliases -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
